#!/usr/bin/env bash
# One-time preparation of an Ubuntu 22.04/24.04 Azure VM for In2ERP. Run as root:
#   sudo bash setup-vm.sh <deploy-user> <public-url>
#     <public-url>  the address users open, e.g. https://in2erp.example.com
# Installs Docker if missing, creates /opt/in2erp and writes /opt/in2erp/.env with freshly
# generated secrets. HTTPS is terminated by the host nginx (see nginx-site.conf).
# The secrets stay on the VM; nothing is printed. Safe to re-run: an existing .env is kept.
set -euo pipefail
DEPLOY_USER=${1:?usage: setup-vm.sh <deploy-user> <public-url>}
PUBLIC_URL=${2:?usage: setup-vm.sh <deploy-user> <public-url>}
PUBLIC_URL=${PUBLIC_URL%/}
APP_DIR=/opt/in2erp

case "$PUBLIC_URL" in
  https://*) COOKIE_SECURE=true ;;
  http://*)  COOKIE_SECURE=false
             echo "WARNING: plain HTTP. Sign-in traffic is not encrypted; use HTTPS for real use." ;;
  *) echo "public-url must start with https:// or http://" >&2; exit 1 ;;
esac

if ! command -v docker >/dev/null; then
  echo "Installing Docker..."
  apt-get update -q
  apt-get install -y -q ca-certificates curl openssl
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -q
  apt-get install -y -q docker-ce docker-ce-cli containerd.io docker-compose-plugin
fi

id "$DEPLOY_USER" >/dev/null 2>&1 || adduser --disabled-password --gecos "" "$DEPLOY_USER"
usermod -aG docker "$DEPLOY_USER"
install -d -o "$DEPLOY_USER" -g "$DEPLOY_USER" -m 750 "$APP_DIR" "$APP_DIR/backups"

if [ -f "$APP_DIR/.env" ]; then
  echo "$APP_DIR/.env exists; keeping it."
else
  rand() { openssl rand -base64 64 | tr -d '\n/+=' | cut -c1-48; }
  PG_PASSWORD=$(rand)
  (
    umask 077
    cat > "$APP_DIR/.env" <<EOF
# In2ERP production settings (generated by setup-vm.sh). Private: never commit or share.
HTTP_PORT=${HTTP_PORT:-8091}
POSTGRES_PASSWORD=$PG_PASSWORD

APP_ENV=production
DATABASE_URL=postgresql+asyncpg://erpuser:$PG_PASSWORD@postgres:5432/in2it_erp
JWT_SECRET_KEY=$(rand)
SECRET_KEY=$(rand)
CORS_ORIGINS=["$PUBLIC_URL"]
TRUST_PROXY_HEADERS=true
REFRESH_COOKIE_SECURE=$COOKIE_SECURE
SEED_ON_STARTUP=false

# Local password sign-in (all | break_glass_only | disabled). Default: all until Entra is set.
#LOCAL_AUTH_MODE=all
#BREAK_GLASS_EMAILS=["admin@in2it.com"]

# Microsoft Entra ID (docs/entra-setup.md)
#ENTRA_TENANT_ID=
#ENTRA_SPA_CLIENT_ID=
#ENTRA_API_CLIENT_ID=
EOF
  )
  chown "$DEPLOY_USER:$DEPLOY_USER" "$APP_DIR/.env"
  chmod 600 "$APP_DIR/.env"
  echo "Wrote $APP_DIR/.env with new random secrets."
fi

echo "Done. Next: add the GitHub secrets and run the deploy workflow (docs/deployment-azure-vm.md)."
